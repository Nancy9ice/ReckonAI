"""Alembic environment.

Two decisions here are load-bearing and both differ from the generated template.

The database URL comes from `reckonai.config.Settings`, never from
`alembic.ini`. One source of truth for which database a migration runs against,
and it is the same source the application itself reads - including the driver
normalisation, so a migration cannot connect through a different DBAPI than the
service does.

The engine is unpooled. A migration is a short-lived process that opens one
connection and exits, and the connection budget in specs/tech-stack.md section
11 counts a pre-deploy migration against the same cap as the web service.
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context

from reckonai import models
from reckonai.config import get_settings
from reckonai.db import create_short_lived_engine

config = context.config

if config.config_file_name is not None:
    # `disable_existing_loggers=False` is not a preference. `fileConfig`
    # defaults it to True, which **disables every logger already configured** -
    # so running Alembic in-process silences `reckonai.web`,
    # `reckonai.worker` and everything else for the life of the process.
    #
    # It does not show up when Alembic runs as its own process, which is how
    # Render invokes it through `preDeployCommand`. It showed up in the test
    # suite the moment a session fixture migrated the database in-process:
    # `tests/test_health.py::test_readiness_failure_leaks_no_credential`
    # started failing because the warning it asserts on was never emitted,
    # while passing when that module ran alone.
    fileConfig(config.config_file_name, disable_existing_loggers=False)

# Autogenerate and `alembic check` both compare the database against this.
#
# Importing `reckonai.models` is what makes it complete: the package imports
# every model module, and a table whose module was never imported is absent
# from the metadata - which autogenerate reads as a table to **drop**. Phase 3
# adds eight more tables and must add them to `reckonai/models/__init__.py` for
# the same reason.
#
# Phase 1 left this as `None` deliberately, since it had no tables and an
# autogenerated revision would have been empty either way.
target_metadata = models.Base.metadata


def _database_url() -> str:
    return get_settings().sqlalchemy_url


def run_migrations_offline() -> None:
    """Emit SQL without connecting, for reviewing a migration before it runs."""
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        dialect_opts={"paramstyle": "named"},
    )

    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    """Run migrations against a live database."""
    engine = create_short_lived_engine(_database_url())
    try:
        with engine.connect() as connection:
            context.configure(
                connection=connection,
                target_metadata=target_metadata,
            )
            with context.begin_transaction():
                context.run_migrations()
    finally:
        engine.dispose()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
