def make_order(tenant: Tenant, total: Money, **kwargs: object) -> Order:
    return Order(
        tenant_id=tenant.id,
        external_ref=kwargs.pop("external_ref", f"ORD-{uuid4().hex[:8]}"),
        total=total,
        placed_at=PLACED_AT,
        **kwargs,
    )


