@pytest.mark.parametrize("currency", supported_currencies())
def test_money_round_trips_through_the_database(
    session: Session, tenant: Tenant, currency: str
) -> None:
    """requirements.md D4's evidence, for every currency in the registry.

    Including both exponent edges, because a composite that stored the amount
    and dropped the exponent would look correct for USD and wrong for JPY and
    KWD - and USD is what a hand-written test would have used.
    """
    total = Money(Decimal("1234.5"), currency).quantize()
    order = make_order(tenant, total)

    session.add(order)
    session.flush()
    session.expire(order)

    assert order.total == total
    assert order.total.currency == currency
    assert isinstance(order.total, Money)


def test_the_composite_writes_both_columns(
    session: Session, tenant: Tenant
) -> None:
    """Read the raw columns, not the mapped attribute.

    This is what proves the currency actually reached the database rather than
    being reconstructed from a default on the way back out.
    """
    order = make_order(tenant, Money("160.00", "EUR"))
    session.add(order)
    session.flush()

    row = session.execute(
        Order.__table__.select().where(Order.__table__.c.id == order.id)
    ).one()

    assert row.total_amount == Decimal("160.000000")
    assert row.total_currency == "EUR"


def test_an_over_precise_amount_is_rounded_by_the_column(
    session: Session, tenant: Tenant
) -> None:
    """requirements.md D5's trap, asserted rather than avoided.

    `NUMERIC(20, 6)` **silently rounds** on insert; it does not raise. So a
    `Money` carrying fifteen decimal places - which is what a PayPal rate
    multiplication produces - persists as six. That is a caller error, and this
    test documents what the database does with one so nobody discovers it
    while chasing a residue.
    """
    order = make_order(tenant, Money(Decimal("104.04507010764778050"), "USD"))

    session.add(order)
    session.flush()
    session.expire(order)

    assert order.total.amount == Decimal("104.045070")
    assert order.total != Money(Decimal("104.04507010764778050"), "USD")


def test_a_null_money_pair_reads_back_as_none(
    session: Session, tenant: Tenant
) -> None:
    """A nullable composite: what does SQLAlchemy hand back when both columns
    are NULL?

    This is asserted rather than assumed because the alternative - constructing
    `Money(None, None)` - would raise `InvalidAmount` on every load of a
    commission rule with no fixed component, which is most of them.
    """
    rule = CommissionRule(
        tenant_id=tenant.id,
        rate=Decimal("0.100000"),
        valid_from=PLACED_AT,
        fixed=None,
    )

    session.add(rule)
    session.flush()
    session.expire(rule)

    assert rule.fixed is None


def test_a_set_money_pair_reads_back_as_money(
    session: Session, tenant: Tenant
) -> None:
    rule = CommissionRule(
        tenant_id=tenant.id,
        rate=Decimal("0.100000"),
        valid_from=PLACED_AT,
        fixed=Money("0.30", "USD"),
    )

    session.add(rule)
    session.flush()
    session.expire(rule)

    assert rule.fixed == Money("0.30", "USD")


