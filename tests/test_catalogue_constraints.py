def test_an_order_item_cannot_reference_another_tenants_order(
    session: Session, tenant: Tenant, seller: Seller
) -> None:
    """requirements.md D7. The composite foreign key is what makes a
    cross-tenant link unwritable rather than merely discouraged.

    A single-column FK on `order_id` would accept this row happily, and the
    first symptom would be one marketplace's reconciliation including another
    marketplace's line item.
    """
    other = Tenant(name="GadgetBazaar", slug=f"gadget-{uuid4().hex[:8]}")
    session.add(other)
    session.flush()

    other_order = make_order(other, Money("50.00", "USD"))
    session.add(other_order)
    session.flush()

    # The item belongs to `tenant`, but points at `other`'s order.
    session.add(
        OrderItem(
            tenant_id=tenant.id,
            order_id=other_order.id,
            seller_id=seller.id,
            external_ref="item-1",
            quantity=1,
            unit_price=Money("50.00", "USD"),
            line_total=Money("50.00", "USD"),
        )
    )

    with pytest.raises(IntegrityError, match="fk_order_item_tenant_id_order_id"):
        session.flush()


