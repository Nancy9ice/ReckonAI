"""The catalogue tables, against a real database.

These tests need Postgres, not SQLite and not a mock, for two reasons that are
the whole point of the module:

  - `composite()` is the one piece of ORM machinery in this phase
    (specs/2026-11-07-canonical-core/requirements.md D4), and it is load-bearing
    for every table Phase 3 adds. Checking it against real `NUMERIC` and
    `VARCHAR` columns is the difference between knowing it works and assuming.
  - A `CHECK` constraint and a composite `FOREIGN KEY` only exist in the
    database. A test that asserts them through the ORM proves nothing about the
    DDL, and a constraint lost in an autogenerated migration would leave every
    ORM-level test passing.

Each test runs inside a transaction that is rolled back, so the suite leaves no
rows behind and the tests do not depend on each other's order.
"""

from __future__ import annotations

from collections.abc import Iterator
from datetime import UTC, datetime
from decimal import Decimal
from uuid import uuid4

import pytest
from sqlalchemy import Engine
from sqlalchemy.exc import DBAPIError, IntegrityError
from sqlalchemy.orm import Session

from reckonai.models import (
    CommissionRule,
    Order,
    OrderItem,
    Seller,
    Tenant,
)
from reckonai.money import InvalidAmount, Money, supported_currencies

PLACED_AT = datetime(2026, 11, 7, 12, 0, tzinfo=UTC)


@pytest.fixture
def session(migrated_database: Engine) -> Iterator[Session]:
    """A session whose work is always rolled back.

    The schema comes from `migrated_database` - the Alembic revision, not
    `Base.metadata.create_all`. See that fixture in `conftest.py` for why,
    including the test-isolation failure that made the difference matter. The
    useful consequence here is that these constraint tests now exercise the DDL
    a migration produced, so a `CHECK` lost in autogenerate fails this module
    too.

    `join_transaction_mode="create_savepoint"` is load-bearing, not decoration.
    Many tests here provoke an `IntegrityError`, which rolls the session's
    transaction back - and without a savepoint that also tears down the outer
    transaction this fixture owns, so the teardown warns
    "transaction already deassociated from connection" and the next statement
    runs outside a transaction. With a savepoint, a failed flush unwinds only
    to the savepoint and the enclosing transaction survives to be rolled back
    here.
    """
    connection = migrated_database.connect()
    transaction = connection.begin()
    with Session(bind=connection, join_transaction_mode="create_savepoint") as session:
        yield session
    transaction.rollback()
    connection.close()


