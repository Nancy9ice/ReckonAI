def test_a_fixed_amount_without_a_currency_is_rejected(
    session: Session, tenant: Tenant
) -> None:
    """specs/tech-stack.md section 9.3 calls this a hard failure, not a warning.

    Written through the raw table rather than the ORM, because `composite()`
    makes it unrepresentable through the mapped attribute - which is the point
    of D4, and exactly why the DDL check still has to exist for rows written by
    a migration, a seed script or a hand-typed INSERT.
    """
    # The statement executes immediately, so the constraint fires here rather
    # than at a later flush - unlike the ORM paths elsewhere in this module.
    with pytest.raises(DBAPIError, match="ck_commission_rule_fixed_pair"):
        session.execute(
            CommissionRule.__table__.insert().values(
                id=uuid4(),
                tenant_id=tenant.id,
                rate=Decimal("0.1"),
                valid_from=PLACED_AT,
                fixed_amount=Decimal("0.30"),
                fixed_currency=None,
            )
        )


