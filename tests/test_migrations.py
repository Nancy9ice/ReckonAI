"""The migrations apply, reverse, and match the models.

A revision that cannot be reversed is a revision that was never tested against
a copy of production, and every later phase would inherit that. The baseline
established the property while there was no schema to risk; Phase 2 added the
first revision with tables in it, and `test_the_models_and_the_migrations_agree`
is what keeps the two from drifting apart.
"""

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import Engine, text

from expected_schema import DATABASE_TABLES, MODEL_TABLES

PROJECT_ROOT = Path(__file__).resolve().parent.parent


@pytest.fixture
def alembic_config(database_url: str) -> Config:
    # env.py reads the URL from Settings, so nothing is set on the Config here.
    # That is the point of leaving sqlalchemy.url empty in alembic.ini.
    return Config(str(PROJECT_ROOT / "alembic.ini"))


@pytest.fixture
def at_base(alembic_config: Config) -> Iterator[Config]:
    """Run each test from a known-empty state, and leave the database at head."""
    command.downgrade(alembic_config, "base")
    yield alembic_config
    command.upgrade(alembic_config, "head")


def _version_rows(engine: Engine) -> list[str]:
    query = text("SELECT version_num FROM alembic_version")
    with engine.connect() as connection:
        return [row[0] for row in connection.execute(query)]


def test_upgrade_applies_the_head_revision(
    at_base: Config, engine: Engine
) -> None:
    command.upgrade(at_base, "head")

    head = ScriptDirectory.from_config(at_base).get_current_head()
    assert _version_rows(engine) == [head]


def _public_tables(engine: Engine) -> list[str]:
    query = text(
        "SELECT table_name FROM information_schema.tables "
        "WHERE table_schema = 'public'"
    )
    with engine.connect() as connection:
        return sorted(row[0] for row in connection.execute(query))


def test_upgrade_creates_the_catalogue_tables(
    at_base: Config, engine: Engine
) -> None:
    """The five tables specs/roadmap.md Phase 2 names, and nothing else.

    Replaced Phase 1's assertion that the schema held only `alembic_version`.
    That check was correct for an empty baseline and is now the inverse of the
    truth, so it is rewritten rather than deleted - the useful property is
    still "exactly these tables", not "some tables exist".
    """
    command.upgrade(at_base, "head")

    assert _public_tables(engine) == list(DATABASE_TABLES)


def test_the_models_and_the_migrations_agree(at_base: Config) -> None:
    """`alembic check`, as a test.

    A model changed without a migration is otherwise invisible until the next
    Render deploy, where `preDeployCommand` applies a revision that no longer
    matches the code being deployed. Phase 3 adds eight tables and this is what
    will catch the one whose revision was forgotten.

    `command.check` raises `AutogenerateDiffsDetected` when they disagree, so
    the assertion is that it returns at all.
    """
    command.upgrade(at_base, "head")

    command.check(at_base)


def test_every_catalogue_table_carries_a_tenant_id(
    at_base: Config, engine: Engine
) -> None:
    """The tenant rule, checked against the **database** rather than the models.

    `tests/test_models_schema.py` asserts this over `Base.metadata`, which is
    what a developer edits. This asserts it over the schema a migration
    actually produced, which is what a query runs against. Both can be true and
    only one of them is what the deployed system has.
    """
    command.upgrade(at_base, "head")

    query = text(
        "SELECT table_name FROM information_schema.columns "
        "WHERE table_schema = 'public' AND column_name = 'tenant_id' "
        "AND is_nullable = 'NO'"
    )
    with engine.connect() as connection:
        scoped = sorted(row[0] for row in connection.execute(query))

    # Every table except `tenant`, which is what a `tenant_id` points at.
    expected = [name for name in MODEL_TABLES if name != "tenant"]

    assert scoped == expected


def test_downgrade_reverses_every_revision(
    at_base: Config, engine: Engine
) -> None:
    """Alembic keeps `alembic_version` across a downgrade and empties it.

    Asserting an empty schema here would fail against correct behaviour - the
    table survives `downgrade base` by design, and only the row is removed. So
    the two assertions are separate: no version row, and none of the catalogue
    tables left behind.

    The second is what catches a `downgrade()` that drops in the wrong
    dependency order, or forgets a table entirely.
    """
    command.upgrade(at_base, "head")
    command.downgrade(at_base, "base")

    assert _version_rows(engine) == []
    assert _public_tables(engine) == ["alembic_version"]


def test_the_cycle_is_repeatable(at_base: Config, engine: Engine) -> None:
    head = ScriptDirectory.from_config(at_base).get_current_head()

    command.upgrade(at_base, "head")
    command.downgrade(at_base, "base")
    command.upgrade(at_base, "head")

    assert _version_rows(engine) == [head]
