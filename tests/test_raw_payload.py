"""The raw payload store keeps the evidence, and keeps it exactly.

specs/2026-11-08-canonical-events/validation.md C18, and the insert half of C4.

Everything here runs against the migrated schema via `migrated_database`, not
against `Base.metadata.create_all`. That is the point: a `CHECK` or a unique
constraint lost in an autogenerated revision fails these tests rather than
passing against a schema the deployed system does not have.
"""

from __future__ import annotations

import hashlib
import json
import uuid
from datetime import UTC, datetime

import pytest
from sqlalchemy import Engine, delete, select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from reckonai.models import Tenant
from reckonai.models.payloads import RawPayload

#: A payload with the three things a JSONB round-trip can get wrong: nesting, a
#: non-ASCII string in real data, and an amount that must stay a string.
#:
#: specs/tech-stack.md section 13 bans pictographs, not all non-ASCII - a
#: seller name with a diacritic is ordinary marketplace data, and if it does not
#: survive storage the evidence is corrupt.
NESTED_BODY = {
    "id": "5O190127TN364715T",
    "payee": {"merchant_id": "C24NAWELTTHXJ", "display_name": "Café Zoë"},
    "seller_receivable_breakdown": {
        "gross_amount": {"value": "100.00", "currency_code": "USD"},
        "platform_fees": [
            {"amount": {"value": "10.00", "currency_code": "USD"}},
        ],
    },
    "links": [{"rel": "up", "href": "https://api-m.sandbox.paypal.com/x"}],
}


def _sha256(body: dict) -> str:
    """Hash the canonical serialization, as a caller would."""
    canonical = json.dumps(body, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


@pytest.fixture
def tenant(migrated_database: Engine) -> uuid.UUID:
    """One tenant, removed afterwards so the table is left as it was found."""
    tenant_id = uuid.uuid4()

    with Session(migrated_database) as session:
        session.add(
            Tenant(id=tenant_id, name="Payload Fixture", slug=f"pf-{tenant_id.hex[:8]}")
        )
        session.commit()

    yield tenant_id

    with Session(migrated_database) as session:
        session.execute(delete(RawPayload).where(RawPayload.tenant_id == tenant_id))
        session.execute(delete(Tenant).where(Tenant.id == tenant_id))
        session.commit()


def _payload(tenant_id: uuid.UUID, **overrides: object) -> RawPayload:
    body = overrides.pop("body", NESTED_BODY)
    fields: dict[str, object] = {
        "tenant_id": tenant_id,
        "source": "paypal",
        "source_record_type": "capture",
        "source_record_id": "5O190127TN364715T",
        "endpoint": "GET /v2/payments/captures/{id}",
        "retrieved_at": datetime(2026, 11, 8, 12, 0, tzinfo=UTC),
        "body": body,
        "body_sha256": _sha256(body),  # type: ignore[arg-type]
    }
    fields.update(overrides)
    return RawPayload(**fields)  # type: ignore[arg-type]


def test_a_nested_payload_round_trips_unchanged(
    migrated_database: Engine, tenant: uuid.UUID
) -> None:
    """The body comes back identical, diacritic and amount-strings included.

    specs/paypal-fields.md is explicit about why the body is kept verbatim:
    PayPal returned three fields that neither of its published contracts
    declares, and two stopped being returned a day later. A deserializer in
    front of this would have discarded them silently.
    """
    with Session(migrated_database) as session:
        session.add(_payload(tenant))
        session.commit()

    with Session(migrated_database) as session:
        stored = session.scalars(
            select(RawPayload).where(RawPayload.tenant_id == tenant)
        ).one()

        assert stored.body == NESTED_BODY
        assert stored.body["payee"]["display_name"] == "Café Zoë"
        # Still a string, not a float. A JSON number here would be an IEEE-754
        # double by the time anything read it (specs/tech-stack.md section 2).
        gross = stored.body["seller_receivable_breakdown"]["gross_amount"]["value"]
        assert isinstance(gross, str)
        assert gross == "100.00"


def test_an_unchanged_re_read_is_refused(
    migrated_database: Engine, tenant: uuid.UUID
) -> None:
    """The same document twice stores once.

    This is what makes re-running ingestion idempotent in Phases 6, 7 and 9 -
    a property of the database rather than a promise made by two different
    connectors.
    """
    with Session(migrated_database) as session:
        session.add(_payload(tenant))
        session.commit()

    with Session(migrated_database) as session:
        session.add(_payload(tenant))

        with pytest.raises(IntegrityError):
            session.commit()


def test_a_changed_re_read_stores_a_second_row(
    migrated_database: Engine, tenant: uuid.UUID
) -> None:
    """A *different* payload for the same record is kept alongside the first.

    Deliberate, and the only way specs/roadmap.md Phase 7's payload diff can
    see a field that stopped being returned. The observed case: a capture's
    whole `seller_receivable_breakdown` disappears while it is PENDING, and an
    open dispute puts it there.
    """
    dropped = "seller_receivable_breakdown"
    pending = {k: v for k, v in NESTED_BODY.items() if k != dropped}

    with Session(migrated_database) as session:
        session.add(_payload(tenant))
        session.add(_payload(tenant, body=pending, body_sha256=_sha256(pending)))
        session.commit()

    with Session(migrated_database) as session:
        stored = session.scalars(
            select(RawPayload).where(RawPayload.tenant_id == tenant)
        ).all()

        assert len(stored) == 2
        assert sum("seller_receivable_breakdown" in row.body for row in stored) == 1


def test_the_same_body_under_a_different_record_type_inserts(
    migrated_database: Engine, tenant: uuid.UUID
) -> None:
    """The unique constraint is scoped by record type, not by hash alone.

    The same document read as a capture and as part of an order is two pieces
    of evidence about two things, and Phase 7 reads refunds through the order
    precisely because the read path changes what is in it.
    """
    with Session(migrated_database) as session:
        session.add(_payload(tenant))
        session.add(_payload(tenant, source_record_type="order"))
        session.commit()

    with Session(migrated_database) as session:
        assert (
            len(
                session.scalars(
                    select(RawPayload).where(RawPayload.tenant_id == tenant)
                ).all()
            )
            == 2
        )


def test_an_unknown_source_is_rejected(
    migrated_database: Engine, tenant: uuid.UUID
) -> None:
    """`source` is checked, because it is the only place origin is stored.

    requirements.md D3: a financial record's origin is reached by joining its
    payload and is never repeated on the record. A typo here would therefore
    mislabel every record pointing at this row.
    """
    with Session(migrated_database) as session:
        session.add(_payload(tenant, source="stripe"))

        with pytest.raises(IntegrityError):
            session.commit()


def test_retrieved_at_is_not_server_defaulted(migrated_database: Engine) -> None:
    """`retrieved_at` is when the payload was fetched, and only the caller knows.

    `created_at` is when the row was written. A replayed or backfilled payload
    does not share the two, and defaulting this column would quietly present an
    insert time as a provider retrieval time - the substitution
    specs/mission.md P3 forbids.
    """
    column = RawPayload.__table__.c.retrieved_at

    assert column.server_default is None
    assert column.default is None
    assert not column.nullable


def test_the_payload_table_is_tenant_scoped() -> None:
    """The table most easily rationalised as infrastructure is not exempt.

    It holds a marketplace's financial documents, so specs/tech-stack.md
    section 10 applies to it like any other table.
    """
    assert "tenant_id" in RawPayload.__table__.c
    assert not RawPayload.__table__.c.tenant_id.nullable
